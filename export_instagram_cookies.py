"""
Instagram Cookie Exporter for Universal Downloader
====================================================
Opens Chrome, asks you to log into Instagram,
then extracts cookies and saves them.

Usage: python export_instagram_cookies.py
"""

import os, sys, time, json, subprocess, urllib.request, shutil

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
COOKIES_PATH = os.path.join(PROJECT_ROOT, "cookies.txt")
TEMP_DIR = os.path.join(os.environ.get("TEMP", PROJECT_ROOT), "ud_ig_cookies")
CHROME_PATH = r"C:\Program Files\Google\Chrome\Application\chrome.exe"


def main():
    print("=" * 55)
    print("  Instagram Cookie Exporter")
    print("=" * 55)
    print()

    # Kill any lingering Chrome with our temp dir
    os.system("taskkill /F /IM chrome.exe >nul 2>&1")
    time.sleep(1)

    # Clean and create temp directory
    if os.path.exists(TEMP_DIR):
        try:
            shutil.rmtree(TEMP_DIR)
        except:
            pass
    os.makedirs(TEMP_DIR, exist_ok=True)

    # Launch Chrome with CDP
    print("1. Launching Chrome (new window)...")
    proc = subprocess.Popen(
        [
            CHROME_PATH,
            "--remote-debugging-port=9222",
            f"--user-data-dir={TEMP_DIR}",
            "--no-first-run",
            "--no-default-browser-check",
            "https://www.instagram.com/",
        ],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    time.sleep(3)

    print("2. Chrome opened! Go to the Chrome window and LOG INTO Instagram.")
    print("   (If you see the Instagram login page, enter your credentials)")
    print()

    # Wait for user log in by polling for sessionid cookie
    max_wait = 300  # 5 minutes max
    found = False

    for i in range(max_wait):
        try:
            resp = urllib.request.urlopen("http://localhost:9222/json", timeout=2)
            tabs = json.loads(resp.read())
            if tabs:
                tab_id = tabs[0].get("id", "")
                import asyncio, websockets

                async def check_cookies():
                    async with websockets.connect(
                        tabs[0]["webSocketDebuggerUrl"]
                    ) as ws:
                        msg = json.dumps({"id": 1, "method": "Network.getAllCookies"})
                        await ws.send(msg)
                        result = json.loads(await ws.recv())
                        cookies = result.get("result", {}).get("cookies", [])
                        return cookies

                try:
                    cookies = asyncio.run(check_cookies())
                    insta = [c for c in cookies if "instagram" in c.get("domain", "")]
                    sid = [c for c in insta if c["name"] == "sessionid"]

                    if sid:
                        found = True
                        print(
                            f"\n3. Logged in! sessionid found: {sid[0]['value'][:10]}..."
                        )

                        # Write cookies.txt
                        with open(COOKIES_PATH, "w") as f:
                            f.write(
                                "# Netscape HTTP Cookie File\n# Generated by export_instagram_cookies.py\n\n"
                            )
                            for c in cookies:
                                if "instagram" not in c.get("domain", "").lower():
                                    continue
                                d = c.get("domain", ".instagram.com")
                                if not d.startswith("."):
                                    d = "." + d
                                f.write(
                                    f"{d}\tTRUE\t{c.get('path', '/')}\t{'TRUE' if c.get('secure') else 'FALSE'}\t{int(c.get('expires', 0))}\t{c['name']}\t{c['value']}\n"
                                )

                        # Sync to all directories
                        for dest in [
                            PROJECT_ROOT,
                            os.path.join(PROJECT_ROOT, "cookies"),
                            os.path.join(PROJECT_ROOT, "python-service", "cookies"),
                        ]:
                            shutil.copy2(
                                COOKIES_PATH, os.path.join(dest, "cookies.txt")
                            )

                        print(f"   Saved to: {COOKIES_PATH}")
                        print()
                        print("SUCCESS! Instagram cookies exported.")
                        print(
                            "You can now close Chrome and restart the Python service."
                        )
                        return True
                except:
                    pass
        except:
            pass

        if i % 10 == 0 and i > 0:
            print(f"   Waiting for you to log into Instagram... ({i}s)")
        time.sleep(1)

    if not found:
        print("\nTimeout reached. Could not detect login.")
        print("Make sure you logged into Instagram in the Chrome window.")
        return False


if __name__ == "__main__":
    success = main()
    input("\nPress Enter to exit..." if not success else "\nPress Enter to exit...")
